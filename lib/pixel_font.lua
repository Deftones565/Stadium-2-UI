function Font.width(rows)
  local w = 0
  for _, row in ipairs(rows) do w = math.max(w, #row) end
  return w
end

-- The glyph for a Latin-1 character code (upper-case fallback for
-- missing lower case), or nil.
function Font.rows(code)
  local c = string.char(code)
  return G[c] or G[c:upper()]
end

return Font
